type_writer_super() {
    TEXT="$1"
    for ((i=0; i<${#TEXT}; i++)); do
        echo -n "${TEXT:$i:1}"
        printf "\a" 2>/dev/null  # beep kalau terminal support
        sleep 0.01  # lebih cepat untuk teks super panjang
    done
    echo ""
}

