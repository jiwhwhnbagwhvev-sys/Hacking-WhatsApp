show_table() {
    clear
    ROWS=$(tput lines)
    COLS=$(tput cols)
    
    TABLE=(
        "┌───────────────────────────────┐"
        "│           RANKING TOP         │"
        "├───────────────────────────────┤"
        "│ 1. ADMIN                       │"
        "│ 2. USER1                       │"
        "│ 3. USER2                       │"
        "│ 4. GUEST                       │"
        "└───────────────────────────────┘"
    )

    START_ROW=$((ROWS/2 - ${#TABLE[@]}/2))
    for i in "${!TABLE[@]}"; do
        tput cup $((START_ROW + i)) $(( (COLS - ${#TABLE[$i]}) / 2 ))
        echo "${TABLE[$i]}"
    done
}

